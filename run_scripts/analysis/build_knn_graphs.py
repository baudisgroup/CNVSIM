from __future__ import annotations

import argparse
from pathlib import Path
import sys


REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from cnvsim.analysis.config import KNNBuildParams, load_analysis_config
from cnvsim.analysis.knn import build_knn_tables_from_release_ir


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Build root-specific KNN tables from analysis IR and selected parameters."
    )
    parser.add_argument("--release-dir", required=True)
    parser.add_argument("--ir-base-dir", default=None)
    parser.add_argument("--out-base-dir", default=None)
    parser.add_argument("--ir-subdir", default="analysis/ir")
    parser.add_argument("--out-subdir", default="analysis/knn/perroot_selected")
    parser.add_argument("--analysis-config", required=True)
    parser.add_argument(
        "--settings-tsv",
        required=True,
        help="Final selected_parameters.tsv generated by select_subtype_parameters.py.",
    )
    parser.add_argument("--roots", default=None)
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()

    cfg = load_analysis_config(args.analysis_config)
    roots = [r.strip() for r in str(args.roots).split(",") if r.strip()] if args.roots else None
    if roots is not None:
        excluded = set(cfg.excluded_roots)
        roots = [root for root in roots if root not in excluded]
        if not roots:
            raise ValueError("No analysis roots remain after applying excluded_roots.")
    settings = Path(args.settings_tsv)
    if not settings.exists():
        raise FileNotFoundError(settings)

    ir_base = Path(args.ir_base_dir) if args.ir_base_dir else None
    out_base = Path(args.out_base_dir) if args.out_base_dir else None
    result = build_knn_tables_from_release_ir(
        release_dir=Path(args.release_dir),
        ir_subdir=str(args.ir_subdir),
        out_subdir=str(args.out_subdir),
        params_default=KNNBuildParams(),
        settings_tsv=settings,
        roots=roots,
        overwrite=bool(args.overwrite),
        ir_base_dir=ir_base,
        out_base_dir=out_base,
    )

    out_path = (out_base / str(args.out_subdir)) if out_base else (Path(args.release_dir) / str(args.out_subdir))
    print(f"[DONE] KNN tables -> {out_path}")
    print(f"[DONE] parameter source: {settings}; roots written={len(result)}")


if __name__ == "__main__":
    main()
